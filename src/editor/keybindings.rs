//! Editor keybindings module for FlashTeX
//!
//! Implements editor keyboard shortcuts including line manipulation,
//! selection helpers, and LaTeX-specific bindings. Inspired by Overleaf's
//! keybinding set with additions for fast LaTeX authoring.
//!
//! The key feature: Alt+Shift+Down duplicates the current line downward,
//! which is essential when working through algebra â duplicate a line,
//! modify the copy, repeat.

use std::fmt;

// ============================================================================
// Key types
// ============================================================================

/// Modifier keys that can be combined with a base key
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Modifiers {
    pub ctrl: bool,
    pub shift: bool,
    pub alt: bool,
    pub meta: bool,
}

impl Modifiers {
    pub const NONE: Self = Self { ctrl: false, shift: false, alt: false, meta: false };
    pub const CTRL: Self = Self { ctrl: true, shift: false, alt: false, meta: false };
    pub const SHIFT: Self = Self { ctrl: false, shift: true, alt: false, meta: false };
    pub const ALT: Self = Self { ctrl: false, shift: false, alt: true, meta: false };
    pub const ALT_SHIFT: Self = Self { ctrl: false, shift: true, alt: true, meta: false };
    pub const CTRL_SHIFT: Self = Self { ctrl: true, shift: true, alt: false, meta: false };
    pub const META: Self = Self { ctrl: false, shift: false, alt: false, meta: true };

    pub fn is_empty(&self) -> bool {
        !self.ctrl && !self.shift && !self.alt && !self.meta
    }

    pub fn matches(&self, other: &Modifiers) -> bool {
        self.ctrl == other.ctrl
            && self.shift == other.shift
            && self.alt == other.alt
            && self.meta == other.meta
    }
}

impl fmt::Display for Modifiers {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let mut parts = Vec::new();
        if self.ctrl { parts.push("Ctrl"); }
        if self.alt { parts.push("Alt"); }
        if self.shift { parts.push("Shift"); }
        if self.meta { parts.push("Cmd"); }
        write!(f, "{}", parts.join("+"))
    }
}

/// Virtual key codes
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum KeyCode {
    ArrowUp,
    ArrowDown,
    ArrowLeft,
    ArrowRight,
    Enter,
    Tab,
    Backspace,
    Delete,
    Home,
    End,
    PageUp,
    PageDown,
    Escape,
    Char(char),
    F(u8),
}

impl fmt::Display for KeyCode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            KeyCode::ArrowUp => write!(f, "Up"),
            KeyCode::ArrowDown => write!(f, "Down"),
            KeyCode::ArrowLeft => write!(f, "Left"),
            KeyCode::ArrowRight => write!(f, "Right"),
            KeyCode::Enter => write!(f, "Enter"),
            KeyCode::Tab => write!(f, "Tab"),
            KeyCode::Backspace => write!(f, "Backspace"),
            KeyCode::Delete => write!(f, "Delete"),
            KeyCode::Home => write!(f, "Home"),
            KeyCode::End => write!(f, "End"),
            KeyCode::PageUp => write!(f, "PageUp"),
            KeyCode::PageDown => write!(f, "PageDown"),
            KeyCode::Escape => write!(f, "Escape"),
            KeyCode::Char(c) => write!(f, "{}", c),
            KeyCode::F(n) => write!(f, "F{}", n),
        }
    }
}

/// A complete key chord: modifiers + key
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct KeyChord {
    pub modifiers: Modifiers,
    pub key: KeyCode,
}

impl KeyChord {
    pub fn new(modifiers: Modifiers, key: KeyCode) -> Self {
        Self { modifiers, key }
    }

    pub fn plain(key: KeyCode) -> Self {
        Self { modifiers: Modifiers::NONE, key }
    }
}

impl fmt::Display for KeyChord {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.modifiers.is_empty() {
            write!(f, "{}", self.key)
        } else {
            write!(f, "{}+{}", self.modifiers, self.key)
        }
    }
}

